-- Mercado Pago seller-account linking (OAuth).
--
-- Run once in the Supabase SQL Editor. Idempotent.
--
--   mercadopago_oauth_state -> one-time OAuth states (only the sha256 is stored).
--   mercadopago_conexion    -> one linked seller account per user, tokens
--                              encrypted by the server (AES-256-GCM).
-- Both tables are accessed only by the server with the service role key.

CREATE TABLE IF NOT EXISTS public.mercadopago_oauth_state (
  state_hash TEXT PRIMARY KEY,
  id_usuario BIGINT NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
  expira_en  TIMESTAMPTZ NOT NULL,
  usado_en   TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS mercadopago_oauth_state_expira_idx
  ON public.mercadopago_oauth_state (expira_en);

CREATE TABLE IF NOT EXISTS public.mercadopago_conexion (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario        BIGINT NOT NULL UNIQUE REFERENCES public.usuarios (id) ON DELETE CASCADE,
  mp_user_id        BIGINT NOT NULL,
  access_token_enc  TEXT NOT NULL,
  refresh_token_enc TEXT NOT NULL,
  scope             TEXT,
  expira_en         TIMESTAMPTZ NOT NULL,
  estado            TEXT NOT NULL DEFAULT 'Conectada'
                    CHECK (estado IN ('Conectada', 'Reautorizar')),
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Defense in depth: the server uses the service role (bypasses RLS); enabling
-- RLS with no policies keeps these tables unreachable for anon/authenticated keys.
ALTER TABLE public.mercadopago_oauth_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mercadopago_conexion ENABLE ROW LEVEL SECURITY;
