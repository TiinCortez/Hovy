-- 1. Ajuste de combustible y domicilio base del usuario (staff/jefe) -----------
-- Todo es NULLable: un usuario sin configurar no rompe nada. Que el consumo sea
-- obligatorio para calcular el traslado lo valida el backend, no la base.
ALTER TABLE public.usuarios
  ADD COLUMN IF NOT EXISTS domicilio_base      TEXT,
  ADD COLUMN IF NOT EXISTS latitud_base        NUMERIC(10, 7),
  ADD COLUMN IF NOT EXISTS longitud_base       NUMERIC(10, 7),
  ADD COLUMN IF NOT EXISTS combustible_ciudad  TEXT,
  ADD COLUMN IF NOT EXISTS combustible_tipo    TEXT,
  ADD COLUMN IF NOT EXISTS combustible_empresa TEXT,
  ADD COLUMN IF NOT EXISTS combustible_producto TEXT,
  ADD COLUMN IF NOT EXISTS consumo_100km       NUMERIC(6, 2);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'usuarios_combustible_tipo_check'
  ) THEN
    ALTER TABLE public.usuarios
      ADD CONSTRAINT usuarios_combustible_tipo_check
      CHECK (combustible_tipo IS NULL OR combustible_tipo IN ('nafta', 'gasoil', 'gnc'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'usuarios_consumo_100km_check'
  ) THEN
    ALTER TABLE public.usuarios
      ADD CONSTRAINT usuarios_consumo_100km_check
      CHECK (consumo_100km IS NULL OR (consumo_100km > 0 AND consumo_100km <= 100));
  END IF;
END $$;

-- 2. Caché de precios de combustible (fuente: naftas.com.ar) --------------------
-- Una fila por ciudad + empresa + producto. El backend la refresca de forma
-- perezosa cuando `actualizado_en` tiene más de 3 días; si la API falla se sigue
-- usando el último precio guardado.
CREATE TABLE IF NOT EXISTS public.combustible_precios (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ciudad          TEXT NOT NULL,
  empresa         TEXT NOT NULL,
  producto        TEXT NOT NULL,
  tipo            TEXT NOT NULL CHECK (tipo IN ('nafta', 'gasoil', 'gnc')),
  unidad          TEXT NOT NULL CHECK (unidad IN ('l', 'm3')),
  precio          NUMERIC(10, 2) NOT NULL CHECK (precio > 0),
  fecha_vigencia  TIMESTAMPTZ,
  -- La API a veces informa precios de otra ciudad (fromNearby): se guarda el
  -- origen y la precisión para poder avisarle al usuario.
  desde_ciudad    TEXT,
  precision       TEXT,
  actualizado_en  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (ciudad, empresa, producto)
);

CREATE INDEX IF NOT EXISTS combustible_precios_ciudad_idx
  ON public.combustible_precios (ciudad);

-- Defensa en profundidad: solo el backend (service role) accede.
ALTER TABLE public.combustible_precios ENABLE ROW LEVEL SECURITY;
