-- Escribí tus sentencias SQL idempotentes acá abajo:

-- Notificaciones del panel (campana del Header, Dashboard e historial).
--
-- Tres tipos que se CALCULAN en vivo (fn_notificaciones_actuales):
--   ciclo_corte         : el último turno Realizado de un servicio de corte/césped
--                         tiene 15 días o más y el inmueble no tiene turno futuro.
--                         id_referencia = id_turno realizado.
--   nueva_solicitud     : solicitud de contacto en Pendiente. id_referencia = id_solicitud.
--   turno_sin_confirmar : turno en Coordinado.                 id_referencia = id_turno.
--
-- La tabla guarda cada notificación desde que se detecta por primera vez:
--   Activa    -> se muestra en la campana y en el Dashboard.
--   Resuelta  -> dejó de cumplirse sola (la cierra fn_sincronizar_notificaciones).
--   Cancelada -> el admin la eliminó con la X. Se puede restaurar a Activa.
-- El historial muestra Resueltas y Canceladas cerradas en los últimos 60 días.
-- Las filas no se borran: si se borraran, una notificación que sigue
-- cumpliéndose volvería a aparecer como Activa.

-- 1. Tabla -----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.notificaciones (
  id_notificacion    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo               TEXT NOT NULL
                     CHECK (tipo IN ('ciclo_corte', 'nueva_solicitud', 'turno_sin_confirmar')),
  id_referencia      INTEGER NOT NULL,
  id_cliente         INTEGER,          -- destino del botón "Ver cliente" (ciclo_corte)
  mensaje            TEXT NOT NULL,
  fecha_notificacion TIMESTAMPTZ NOT NULL,
  estado             TEXT NOT NULL DEFAULT 'Activa'
                     CHECK (estado IN ('Activa', 'Resuelta', 'Cancelada')),
  fecha_cierre       TIMESTAMPTZ,      -- cuándo pasó a Resuelta o Cancelada
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT notificaciones_tipo_referencia_uq UNIQUE (tipo, id_referencia)
);

CREATE INDEX IF NOT EXISTS notificaciones_estado_idx
  ON public.notificaciones (estado, fecha_cierre DESC);

-- Defensa en profundidad: igual que el resto de las tablas (service role saltea RLS).
ALTER TABLE public.notificaciones ENABLE ROW LEVEL SECURITY;

-- 2. Cálculo en vivo de las notificaciones que aplican hoy --------------------------
CREATE OR REPLACE FUNCTION public.fn_notificaciones_actuales()
RETURNS TABLE (
  tipo               TEXT,
  id_referencia      INTEGER,
  id_cliente         INTEGER,
  mensaje            TEXT,
  fecha_notificacion TIMESTAMPTZ
)
LANGUAGE sql
STABLE
SET search_path = public
AS $$
  WITH hoy AS (
    SELECT (now() AT TIME ZONE 'America/Argentina/Cordoba')::date AS fecha
  ),
  -- Último turno Realizado por inmueble que incluya un servicio de corte o césped.
  ultimos_cortes AS (
    SELECT DISTINCT ON (t.id_inmueble)
      t.id_turno, t.id_inmueble, t.fecha_programada
    FROM turnos t
    WHERE t.estado = 'Realizado'
      AND EXISTS (
        SELECT 1
        FROM detalle_presupuesto dp
        JOIN servicios_catalogo sc ON sc.id_servicio = dp.id_servicio
        WHERE dp.id_presupuesto = t.id_presupuesto
          AND translate(lower(sc.nombre), 'é', 'e') LIKE ANY (ARRAY['%cesped%', '%corte%'])
      )
    ORDER BY t.id_inmueble, t.fecha_programada DESC, t.id_turno DESC
  )
  -- Ciclo de corte
  SELECT
    'ciclo_corte'::text,
    uc.id_turno::integer,
    i.id_cliente::integer,
    format(
      'Césped en %s excede los 15 días sin corte (último corte: %s).',
      coalesce(nullif(concat_ws(', ', i.direccion, i.barrio), ''), 'un inmueble sin dirección')
        || coalesce(' — ' || nullif(concat_ws(' ', cl.nombre, cl.apellido), ''), ''),
      to_char(uc.fecha_programada, 'DD/MM')
    ),
    ((uc.fecha_programada + 15)::timestamp AT TIME ZONE 'America/Argentina/Cordoba')
  FROM ultimos_cortes uc
  JOIN inmuebles i ON i.id_inmueble = uc.id_inmueble
  LEFT JOIN clientes cl ON cl.id_cliente = i.id_cliente
  CROSS JOIN hoy
  WHERE i.activo = TRUE
    AND uc.fecha_programada <= hoy.fecha - 15
    AND NOT EXISTS (
      SELECT 1
      FROM turnos f
      WHERE f.id_inmueble = uc.id_inmueble
        AND f.estado IN ('Coordinado', 'Confirmado', 'En ejecución')
        AND f.fecha_programada >= hoy.fecha
    )

  UNION ALL

  -- Nueva solicitud de contacto
  SELECT
    'nueva_solicitud'::text,
    s.id_solicitud::integer,
    NULL::integer,
    format(
      '%s solicitó contacto%s.',
      coalesce(nullif(concat_ws(' ', s.nombre, s.apellido), ''), 'Un cliente'),
      coalesce(' para ' || nullif(trim(s.servicio), ''), '')
    ),
    s.created_at
  FROM solicitudes_visita s
  WHERE s.estado = 'Pendiente'

  UNION ALL

  -- Turno sin confirmar (Coordinado)
  SELECT
    'turno_sin_confirmar'::text,
    t.id_turno::integer,
    i.id_cliente::integer,
    format(
      'El turno del %s en %s sigue sin confirmar.',
      to_char(t.fecha_programada, 'DD/MM'),
      coalesce(nullif(concat_ws(', ', i.direccion, i.barrio), ''), 'un inmueble sin dirección')
    ),
    now()   -- solo se usa la primera vez que se detecta (después no se pisa)
  FROM turnos t
  LEFT JOIN inmuebles i ON i.id_inmueble = t.id_inmueble
  WHERE t.estado = 'Coordinado';
$$;

-- 3. Sincronización: alta de nuevas, cierre de resueltas y lista de activas ------------
-- La llama GET /api/notificaciones (campana y Dashboard).
CREATE OR REPLACE FUNCTION public.fn_sincronizar_notificaciones()
RETURNS SETOF public.notificaciones
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_claves TEXT[];
BEGIN
  SELECT coalesce(array_agg(a.tipo || ':' || a.id_referencia), '{}')
  INTO v_claves
  FROM fn_notificaciones_actuales() a;

  -- Nuevas -> Activa. Una Resuelta que vuelve a cumplirse se reactiva.
  -- Una Cancelada no se toca: solo vuelve si el admin la restaura.
  INSERT INTO notificaciones AS n (tipo, id_referencia, id_cliente, mensaje, fecha_notificacion)
  SELECT a.tipo, a.id_referencia, a.id_cliente, a.mensaje, a.fecha_notificacion
  FROM fn_notificaciones_actuales() a
  ON CONFLICT (tipo, id_referencia) DO UPDATE
    SET mensaje      = EXCLUDED.mensaje,
        id_cliente   = EXCLUDED.id_cliente,
        estado       = 'Activa',
        fecha_cierre = NULL
    WHERE n.estado <> 'Cancelada';

  -- Activas que ya no se cumplen -> Resuelta.
  UPDATE notificaciones n
  SET estado = 'Resuelta',
      fecha_cierre = now()
  WHERE n.estado = 'Activa'
    AND NOT ((n.tipo || ':' || n.id_referencia) = ANY (v_claves));

  RETURN QUERY
    SELECT *
    FROM notificaciones n
    WHERE n.estado = 'Activa'
    ORDER BY n.fecha_notificacion DESC, n.id_notificacion DESC;
END;
$$;

-- 4. Permisos: solo el servidor (service role), igual que en la 013 y la 014 ---------
REVOKE ALL ON FUNCTION public.fn_notificaciones_actuales() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.fn_sincronizar_notificaciones() FROM PUBLIC;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON FUNCTION public.fn_notificaciones_actuales() FROM anon;
    REVOKE ALL ON FUNCTION public.fn_sincronizar_notificaciones() FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON FUNCTION public.fn_notificaciones_actuales() FROM authenticated;
    REVOKE ALL ON FUNCTION public.fn_sincronizar_notificaciones() FROM authenticated;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    GRANT EXECUTE ON FUNCTION public.fn_notificaciones_actuales() TO service_role;
    GRANT EXECUTE ON FUNCTION public.fn_sincronizar_notificaciones() TO service_role;
  END IF;
END $$;
