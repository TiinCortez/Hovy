-- 2. Funciones y Triggers ----------------------------------------------------

-- Trigger 1: Al pasar a 'Realizado', validar presupuesto e imputar débito en cuenta corriente
CREATE OR REPLACE FUNCTION public.fn_trg_turno_realizado()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_presupuesto RECORD;
  v_id_cliente INTEGER;
  v_id_cuenta BIGINT;
  v_id_trabajo BIGINT;
BEGIN
  -- Solo se activa cuando pasa a 'Realizado'
  IF NEW.estado = 'Realizado' AND (OLD.estado IS NULL OR OLD.estado <> 'Realizado') THEN
    
    -- 1. Validar que tenga presupuesto asociado
    IF NEW.id_presupuesto IS NULL THEN
      RAISE EXCEPTION 'El turno no puede completarse porque no tiene un presupuesto asociado'
        USING ERRCODE = 'P0001';
    END IF;

    SELECT id_presupuesto, monto_total, estado
    INTO v_presupuesto
    FROM public.presupuestos
    WHERE id_presupuesto = NEW.id_presupuesto;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'El presupuesto asociado al turno (%) no existe', NEW.id_presupuesto
        USING ERRCODE = 'P0001';
    END IF;

    -- 2. El presupuesto debe estar Aceptado y con monto > 0
    IF v_presupuesto.estado <> 'Aceptado' THEN
      RAISE EXCEPTION 'El presupuesto del turno debe estar Aceptado para poder cerrarlo (estado actual: %)', v_presupuesto.estado
        USING ERRCODE = 'P0001';
    END IF;

    IF COALESCE(v_presupuesto.monto_total, 0) <= 0 THEN
      RAISE EXCEPTION 'El presupuesto del turno tiene monto $0 o inválido: no se puede imputar el trabajo'
        USING ERRCODE = 'P0001';
    END IF;

    -- 3. Identificar el cliente (a través del inmueble del turno o de la solicitud/presupuesto)
    SELECT i.id_cliente INTO v_id_cliente
    FROM public.inmuebles i
    WHERE i.id_inmueble = NEW.id_inmueble;

    IF v_id_cliente IS NULL THEN
      SELECT p.id_cliente INTO v_id_cliente
      FROM public.presupuestos p
      WHERE p.id_presupuesto = NEW.id_presupuesto;
    END IF;

    IF v_id_cliente IS NULL THEN
      RAISE EXCEPTION 'No se pudo identificar al cliente asociado al turno %', NEW.id_turno
        USING ERRCODE = 'P0001';
    END IF;

    -- 4. Registrar trabajo si aún no existe
    SELECT id_trabajo INTO v_id_trabajo
    FROM public.trabajos_ejecutados
    WHERE id_turno = NEW.id_turno;

    IF v_id_trabajo IS NULL THEN
      INSERT INTO public.trabajos_ejecutados (id_turno, fecha_ejecucion)
      VALUES (NEW.id_turno, COALESCE(NEW.fecha_programada, CURRENT_DATE))
      RETURNING id_trabajo INTO v_id_trabajo;
    END IF;

    -- 5. Obtener o crear la cuenta corriente del cliente
    INSERT INTO public.cuentas_corrientes (id_cliente, saldo, estado, ultima_actualizacion)
    VALUES (v_id_cliente, 0.00, 'Pendiente', now())
    ON CONFLICT (id_cliente) DO NOTHING;

    SELECT id_cuenta INTO v_id_cuenta
    FROM public.cuentas_corrientes
    WHERE id_cliente = v_id_cliente;

    -- 6. Registrar movimiento de Débito (si no fue registrado previamente para este trabajo)
    IF NOT EXISTS (
      SELECT 1 FROM public.movimientos_cuenta
      WHERE id_trabajo = v_id_trabajo AND tipo = 'Debito'
    ) THEN
      INSERT INTO public.movimientos_cuenta (
        id_cuenta,
        tipo,
        monto,
        concepto,
        id_presupuesto,
        id_trabajo,
        fecha
      ) VALUES (
        v_id_cuenta,
        'Debito',
        v_presupuesto.monto_total,
        'Trabajo #' || v_id_trabajo || ' - Presupuesto #' || NEW.id_presupuesto,
        NEW.id_presupuesto,
        v_id_trabajo,
        now()
      );

      -- 7. Actualizar saldo acumulado de la cuenta corriente
      UPDATE public.cuentas_corrientes
      SET saldo = saldo + v_presupuesto.monto_total,
          estado = CASE WHEN (saldo + v_presupuesto.monto_total) > 0 THEN 'Pendiente' ELSE 'Al dia' END,
          ultima_actualizacion = now()
      WHERE id_cuenta = v_id_cuenta;
    END IF;

  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_turno_realizado ON public.turnos;
CREATE TRIGGER trg_turno_realizado
  AFTER UPDATE OF estado ON public.turnos
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_trg_turno_realizado();

-- Trigger 2: Bloquear la cancelación de un turno si ya tiene trabajo/imputación registrada
CREATE OR REPLACE FUNCTION public.fn_trg_turno_cancelado()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.estado = 'Cancelado' AND OLD.estado <> 'Cancelado' THEN
    IF EXISTS (SELECT 1 FROM public.trabajos_ejecutados WHERE id_turno = OLD.id_turno) THEN
      RAISE EXCEPTION 'El turno % ya tiene un trabajo registrado: no se puede cancelar', OLD.id_turno
        USING ERRCODE = 'P0001';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_turno_cancelado ON public.turnos;
CREATE TRIGGER trg_turno_cancelado
  BEFORE UPDATE OF estado ON public.turnos
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_trg_turno_cancelado();

-- 3. Vistas Auxiliares -------------------------------------------------------

CREATE OR REPLACE VIEW public.v_estado_cuenta AS
SELECT
  mc.id_movimiento,
  mc.id_cuenta,
  cc.id_cliente,
  TRIM(CONCAT(c.nombre, ' ', c.apellido)) AS cliente,
  mc.fecha,
  mc.tipo,
  CASE 
    WHEN mc.id_trabajo IS NOT NULL THEN 'Trabajo'
    WHEN p.id_pago IS NOT NULL THEN 'Pago'
    ELSE 'Ajuste'
  END AS origen,
  mc.concepto,
  CASE 
    WHEN mc.tipo = 'Credito' THEN -ABS(mc.monto)
    ELSE ABS(mc.monto)
  END AS importe,
  SUM(
    CASE 
      WHEN mc.tipo = 'Credito' THEN -ABS(mc.monto)
      ELSE ABS(mc.monto)
    END
  ) OVER (
    PARTITION BY mc.id_cuenta 
    ORDER BY mc.fecha, mc.id_movimiento
  ) AS saldo_acumulado,
  mc.id_presupuesto,
  mc.id_trabajo,
  p.id_pago,
  p.medio_pago,
  p.referencia_comprobante,
  p.estado AS estado_pago
FROM public.movimientos_cuenta mc
JOIN public.cuentas_corrientes cc ON cc.id_cuenta = mc.id_cuenta
JOIN public.clientes c ON c.id_cliente = cc.id_cliente
LEFT JOIN public.pagos p ON p.id_movimiento = mc.id_movimiento;

CREATE OR REPLACE VIEW public.v_deudores AS
SELECT
  c.id_cliente,
  TRIM(CONCAT(c.nombre, ' ', c.apellido)) AS cliente,
  c.telefono,
  c.tipo_cliente,
  cc.saldo,
  cc.ultima_actualizacion,
  MAX(CASE WHEN mc.tipo = 'Credito' THEN mc.fecha END) AS ultimo_pago,
  MIN(CASE WHEN mc.tipo = 'Debito' THEN mc.fecha END) AS primer_debito
FROM public.cuentas_corrientes cc
JOIN public.clientes c ON c.id_cliente = cc.id_cliente
LEFT JOIN public.movimientos_cuenta mc ON mc.id_cuenta = cc.id_cuenta
WHERE cc.saldo > 0
GROUP BY c.id_cliente, c.nombre, c.apellido, c.telefono, c.tipo_cliente, cc.saldo, cc.ultima_actualizacion;

