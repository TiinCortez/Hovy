-- Sub-sistema de Cuenta Corriente, Trabajos Ejecutados y Triggers de Turnos
--
-- Ejecutar en el SQL Editor de Supabase. Es idempotente (seguro de re-ejecutar).
--
-- Contenido:
--   1. Tablas base: cuentas_corrientes, movimientos_cuenta, trabajos_ejecutados
--   2. Triggers de integridad:
--      - trg_turno_realizado: imputa automáticamente el trabajo y débito en cuenta corriente
--        al pasar un turno a 'Realizado'. Rechaza con código P0001 si el presupuesto no está
--        'Aceptado' o su monto_total es <= 0.
--      - trg_turno_cancelado: bloquea cancelar un turno si ya tiene un trabajo registrado (P0001).
--   3. Vistas auxiliares:
--      - v_estado_cuenta: historial unificado de débitos (trabajos) y créditos (pagos)
--      - v_deudores: clientes con saldo deudor pendiente

-- 1. Tablas Base -------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.cuentas_corrientes (
  id_cuenta             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente            INTEGER NOT NULL UNIQUE REFERENCES public.clientes (id_cliente) ON DELETE CASCADE,
  saldo                 NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  estado                TEXT NOT NULL DEFAULT 'Al dia'
                        CHECK (estado IN ('Al dia', 'Pendiente', 'Moroso', 'Suspendido')),
  ultima_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS cuentas_corrientes_cliente_idx
  ON public.cuentas_corrientes (id_cliente);

CREATE TABLE IF NOT EXISTS public.trabajos_ejecutados (
  id_trabajo            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_turno              INTEGER NOT NULL UNIQUE REFERENCES public.turnos (id_turno) ON DELETE CASCADE,
  id_operario_lider     INTEGER REFERENCES public.operarios (id_operario) ON DELETE SET NULL,
  fecha_ejecucion       DATE NOT NULL DEFAULT CURRENT_DATE,
  hora_inicio           TIME,
  hora_fin              TIME,
  duracion_real_min     INTEGER,
  observaciones         TEXT,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS trabajos_ejecutados_turno_idx
  ON public.trabajos_ejecutados (id_turno);

CREATE TABLE IF NOT EXISTS public.movimientos_cuenta (
  id_movimiento         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cuenta             BIGINT NOT NULL REFERENCES public.cuentas_corrientes (id_cuenta) ON DELETE CASCADE,
  tipo                  TEXT NOT NULL CHECK (tipo IN ('Debito', 'Credito', 'Ajuste')),
  monto                 NUMERIC(12, 2) NOT NULL,
  concepto              TEXT NOT NULL,
  fecha                 TIMESTAMPTZ NOT NULL DEFAULT now(),
  id_presupuesto        INTEGER REFERENCES public.presupuestos (id_presupuesto) ON DELETE SET NULL,
  id_trabajo            BIGINT REFERENCES public.trabajos_ejecutados (id_trabajo) ON DELETE SET NULL
);

