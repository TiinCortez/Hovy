-- Internal estimate for visits (slice 1).
--
-- Run once in the Supabase SQL Editor. Idempotent: safe to run again.
--
-- Design:
--   solicitud_servicio -> services a visit includes, with the VERIFIED surface
--                         (m2) per service. The estimate is computed as
--                         sum(usuario_servicio.precio_base x superficie_m2).
--   presupuestos.monto_estimado -> reserved column for storing the internal
--                         estimate next to the final price (used in slice 2).
--
-- The estimate is INTERNAL ONLY: it must never be exposed to clients.

-- IMPORTANT (verify before running): the FK column types below must match the
-- real primary key types of the referenced tables. This script assumes BIGINT
-- for solicitudes_visita.id_solicitud and servicios_catalogo.id_servicio. If
-- either is INTEGER (or UUID), change the column type here, or the foreign key
-- creation will fail.

CREATE TABLE IF NOT EXISTS public.solicitud_servicio (
  id_solicitud_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_solicitud          BIGINT NOT NULL
                        REFERENCES public.solicitudes_visita (id_solicitud) ON DELETE CASCADE,
  id_servicio           BIGINT NOT NULL
                        REFERENCES public.servicios_catalogo (id_servicio),
  superficie_m2         NUMERIC(12, 2) NOT NULL CHECK (superficie_m2 > 0),
  UNIQUE (id_solicitud, id_servicio)
);

CREATE INDEX IF NOT EXISTS solicitud_servicio_solicitud_idx
  ON public.solicitud_servicio (id_solicitud);

-- Internal estimate stored on the budget (nullable: old rows have none).
ALTER TABLE public.presupuestos
  ADD COLUMN IF NOT EXISTS monto_estimado NUMERIC(12, 2);
